def import_data():
    with db_manager.get_session() as db:
        # 删除旧数据
        db.query(ProductSectorAllocation).filter(
            ProductSectorAllocation.product_code == "L02798"
        ).delete()

        # 导入多头数据
        for date_str, sector, pct in long_data:
            allocation = ProductSectorAllocation(
                product_code="L02798",
                allocation_date=datetime.strptime(date_str, "%Y-%m-%d").date(),
                sector_name=sector,
                position_type=PositionTypeEnum.LONG,
                allocation_pct=pct
            )
            db.add(allocation)

        # 导入空头数据
        for date_str, sector, pct in short_data:
            allocation = ProductSectorAllocation(
                product_code="L02798",
                allocation_date=datetime.strptime(date_str, "%Y-%m-%d").date(),
                sector_name=sector,
                position_type=PositionTypeEnum.SHORT,
                allocation_pct=pct
            )
            db.add(allocation)

        db.commit()
        print(f"✓ 成功导入 {len(long_data)} 条多头数据")
        print(f"✓ 成功导入 {len(short_data)} 条空头数据")

