def import_data():
    with db_manager.get_session() as db:
        # 删除旧数据
        db.query(ProductSectorAllocation).filter(
            ProductSectorAllocation.product_code == "L03143"
        ).delete()

        # 导入数据
        for date_str, sector, pct in data:
            # 判断是否为期货空头
            if "期货" in sector:
                position_type = PositionTypeEnum.SHORT
            else:
                position_type = PositionTypeEnum.LONG

            allocation = ProductSectorAllocation(
                product_code="L03143",
                allocation_date=datetime.strptime(date_str, "%Y-%m-%d").date(),
                sector_name=sector,
                position_type=position_type,
                allocation_pct=pct
            )
            db.add(allocation)

        db.commit()
        print(f"✓ 成功导入 {len(data)} 条行业配置数据")

if __name__ == "__main__":
    import_data()
